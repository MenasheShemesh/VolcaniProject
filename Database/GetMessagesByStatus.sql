ALTER PROCEDURE [dbo].[GetMessagesByStatus]
	  @Status int
AS
BEGIN

	SELECT t1.MESSAGE_ID, t2.WORKER_FIRST_NAME, t2.WORKER_LAST_NAME,
	       t2.WORKER_CITY, t2.WORKER_STREET, t2.WORKER_HOUSE_NUMBER,
	       t1.MESSAGE_PHONE_PREFIX, t1.MESSAGE_PHONE_NUMBER, t1.MESSAGE_CONTENT,
	       t1.MESSAGE_STATUS as MESSAGE_STATUS_ID, t3.STATUS_DESCRIPTION as MESSAGE_STATUS_DESCRIPTION,
	       t1.MESSAGE_CREATE_TIME, t1.MESSAGE_UPDATE_TIME
	FROM dbo.MESSAGES t1
	INNER JOIN dbo.WORKERS t2 ON t1.MESSAGE_WORKER_ID = t2.WORKER_ID
	INNER JOIN dbo.MESSAGE_STATUS t3 ON t1.MESSAGE_STATUS = t3.STATUS_ID
	WHERE MESSAGE_STATUS = @Status;
END;